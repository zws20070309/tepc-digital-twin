function x = norminv(p)
%NORMINV 标准正态分位数 (Acklam 有理近似, 无 Statistics Toolbox 依赖)。
%   符号约定: 有理式 R(q) 的渐近主项是 (c1/d1)*q = -q < 0, 所以 R 本身就是负数:
%   低尾用 +R, 高尾用 -R。曾有误判称"两尾符号写反"(依据是"c,d 首项同号"),
%   实测该前提不成立 —— 反改为 z(0.001)=+3.09、z(0.999)=-4.75 且整体单调递减。
%   单调性与已知分位数由单测锁定。
a = [-3.969683028665376e+01, 2.209460984245205e+02, -2.759285104469687e+02, ...
     1.383577518672690e+02, -3.066479806614716e+01, 2.506628277459239e+00];
b = [-5.447609879822406e+01, 1.615858368580409e+02, -1.556989798598866e+02, ...
     6.680131188771972e+01, -1.328068155288572e+01];
c = [-7.784894002430293e-03, -3.223964580411365e-01, -2.400758277161838e+00, ...
     -2.549732539343734e+00, 4.374664141464968e+00, 2.938163982698783e+00];
d = [7.784695709041462e-03, 3.224671290700398e-01, 2.445134137142996e+00, ...
     3.754408661907416e+00];
plow = 0.02425;
sz0 = size(p);                       % 保持输入形状 (分位数函数按元素作用)
p = double(p(:));
if any(p <= 0) || any(p >= 1)
    error("tepc:uq:BadP","分位数自变量必须在 (0,1)");
end
x = zeros(size(p));
lo = p < plow; hi = p > 1 - plow; mid = ~(lo | hi);
if any(lo)
    q = sqrt(-2 * log(p(lo)));
    x(lo) = (((((c(1)*q + c(2)).*q + c(3)).*q + c(4)).*q + c(5)).*q + c(6)) ./ ...
             ((((d(1)*q + d(2)).*q + d(3)).*q + d(4)).*q + 1);
end
if any(hi)
    q = sqrt(-2 * log(1 - p(hi)));
    x(hi) = -(((((c(1)*q + c(2)).*q + c(3)).*q + c(4)).*q + c(5)).*q + c(6)) ./ ...
              ((((d(1)*q + d(2)).*q + d(3)).*q + d(4)).*q + 1);
end
if any(mid)
    q = p(mid) - 0.5; r = q.^2;
    x(mid) = (((((a(1)*r + a(2)).*r + a(3)).*r + a(4)).*r + a(5)).*r + a(6)).*q ./ ...
              (((((b(1)*r + b(2)).*r + b(3)).*r + b(4)).*r + b(5)).*r + 1);
end
x = reshape(x, sz0);
end
